#!/usr/bin/env python3
"""Generate Compass's release-locked registry distfiles without a vendor tarball."""
import argparse
import hashlib
import json
from pathlib import Path

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('lock', type=Path)
p.add_argument('output', type=Path)
a = p.parse_args()
entries = {}
for info in json.loads(a.lock.read_text())['packages'].values():
    url = info.get('resolved')
    if not url or info.get('link'):
        continue
    if not url.startswith('https://registry.npmjs.org/'):
        raise SystemExit(f'Non-registry input: {url}')
    if not info.get('integrity'):
        raise SystemExit(f'Missing integrity: {url}')
    entries[url] = 'mc-' + hashlib.sha256(url.encode()).hexdigest()[:16] + '.tgz'
# Short names keep Portage's exported A below Linux's per-string limit.
if len(set(entries.values())) != len(entries):
    raise SystemExit('Distfile digest-prefix collision')
lines = [
    '# Copyright 2026 Gentoo Authors',
    '# Distributed under the terms of the GNU General Public License v2',
    '',
    f'# @ECLASS: {a.output.name}',
    '# @MAINTAINER:',
    '# Leonid Kopylov <leonchik1976@gmail.com>',
    '# @SUPPORTED_EAPIS: 8',
    '# @BLURB: Upstream npm lockfile distfiles for MongoDB Compass',
    '# Generated by scripts/generate-mongodb-compass-npm-deps.py.',
    '',
    'MONGODB_COMPASS_NPM_SRC_URI="',
]
lines += [f'\t{url} -> {name}' for url, name in sorted(entries.items())]
lines += ['"', '', '# @FUNCTION: mongodb_compass_npm_src_uri', '# @DESCRIPTION:',
          '# Append the release-locked registry archives to SRC_URI.',
          'mongodb_compass_npm_src_uri() {', '\tSRC_URI+=" ${MONGODB_COMPASS_NPM_SRC_URI}"', '}', '']
a.output.write_text('\n'.join(lines))
print(f'Generated {len(entries)} locked npm archives')
