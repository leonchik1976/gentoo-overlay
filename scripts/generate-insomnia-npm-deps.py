#!/usr/bin/env python3
"""Generate Insomnia's public, release-locked npm distfiles from upstream's lock."""
import argparse
import importlib.util
import json
from pathlib import Path
import sys

sys.dont_write_bytecode = True

helper = Path(__file__).resolve().parents[1] / 'dev-util/insomnia/files/insomnia-build.py'
spec = importlib.util.spec_from_file_location('insomnia_build', helper)
build = importlib.util.module_from_spec(spec)
spec.loader.exec_module(build)
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('lock', type=Path)
parser.add_argument('output', type=Path)
args = parser.parse_args()
lock = build.filtered_lock(json.loads(args.lock.read_text()))
entries = {}
for info in lock['packages'].values():
    url = info.get('resolved', '')
    if not url or info.get('link') or url.startswith('git+'):
        continue
    url = build.registry_url(url)
    if not url.startswith('https://registry.npmjs.org/') or not info.get('integrity'):
        raise ValueError(f'Unsupported input: {url}')
    entries[url] = build.archive_name(url)
if len(set(entries.values())) != len(entries):
    raise ValueError('Distfile name collision')
lines = [
    '# Copyright 2026 Gentoo Authors',
    '# Distributed under the terms of the GNU General Public License v2', '',
    '# @ECLASS: insomnia-npm-deps-13.3.1.eclass', '# @MAINTAINER:',
    '# Leonid Kopylov <leonchik1976@gmail.com>', '# @SUPPORTED_EAPIS: 8',
    '# @BLURB: Release-locked public npm inputs for Insomnia',
    '# Generated by scripts/generate-insomnia-npm-deps.py.', '',
    'INSOMNIA_NPM_SRC_URI="',
]
lines += [f'\t{url} -> {name}' for url, name in sorted(entries.items())]
lines += ['"', '', '# @FUNCTION: insomnia_npm_src_uri', '# @DESCRIPTION:',
          '# Append the release-locked npm archives to SRC_URI.',
          'insomnia_npm_src_uri() {', '\tSRC_URI+=" ${INSOMNIA_NPM_SRC_URI}"', '}', '']
args.output.write_text('\n'.join(lines))
print(f'Generated {len(entries)} locked npm archives')
