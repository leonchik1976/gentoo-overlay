#!/usr/bin/env python3
"""Emit Manifest-fetchable npm inputs from Nimbalyst's exact pnpm lockfile.

Usage: generate-nimbalyst-npm-deps.py SOURCE_DIR OUTPUT_ECLASS
No dependency resolution or network access is performed. Both pnpm YAML
documents are read; dependencies retain upstream versions and integrity hashes.
"""

import argparse
from collections import defaultdict
import json
from pathlib import Path
import re

import yaml


def allows(values, target):
    return not values or (f"!{target}" not in values and
                          (target in values or all(v.startswith("!") for v in values)))


def generate(source, output):
    packages = {}
    for document in yaml.safe_load_all((source / "pnpm-lock.yaml").read_text()):
        packages.update(document.get("packages", {}))
    groups = defaultdict(list)
    filenames = {}
    for identifier, package in sorted(packages.items()):
        name, version = identifier.rsplit("@", 1)
        if not allows(package.get("os"), "linux") or not allows(package.get("libc"), "glibc"):
            continue
        arches = [arch for arch, cpu in (("amd64", "x64"), ("arm64", "arm64"))
                  if allows(package.get("cpu"), cpu)]
        if not arches:
            continue
        resolution = package["resolution"]
        if set(resolution) != {"integrity"} or not resolution["integrity"].startswith("sha512-"):
            raise ValueError(f"Unexpected upstream resolution: {identifier}: {resolution}")
        if not re.fullmatch(r"[@a-zA-Z0-9/_.+-]+", name + version):
            raise ValueError(identifier)
        filename = f"nimbalyst-npm-{name.lstrip('@').replace('/', '-')}-{version}.tgz"
        if filename in filenames and filenames[filename] != identifier:
            raise ValueError(f"Distfile collision: {identifier}, {filenames[filename]}")
        filenames[filename] = identifier
        uri = f"https://registry.npmjs.org/{name}/-/{name.rsplit('/', 1)[-1]}-{version}.tgz"
        group = "common" if len(arches) == 2 else arches[0]
        groups[group].append((identifier, resolution["integrity"], filename, uri))
    version = json.loads((source / "packages/electron/package.json").read_text())["version"]
    lines = ["# Copyright 2026 Gentoo Authors", "# Distributed under the terms of the GNU General Public License v2", "",
             f"# @ECLASS: nimbalyst-npm-deps-{version}.eclass", "# @MAINTAINER:",
             "# Leonid Kopylov <leonchik1976@gmail.com>", "# @SUPPORTED_EAPIS: 8",
             "# @BLURB: Exact upstream npm distfiles for Nimbalyst", "# @DESCRIPTION:",
             "# Generated by scripts/generate-nimbalyst-npm-deps.py from the tagged", "# multi-document upstream pnpm lockfile. No registry resolution is used.", "",
             "# @ECLASS_VARIABLE: NIMBALYST_DEPS_VERSION", "# @DESCRIPTION:",
             "# Upstream version from which these immutable inputs were generated.",
             f'NIMBALYST_DEPS_VERSION="{version}"', ""]
    for group in ("common", "amd64", "arm64"):
        lines.extend([f"# @ECLASS_VARIABLE: NIMBALYST_NPM_{group.upper()}",
                      "# @DESCRIPTION:",
                      f"# Array of {group} package identity|SHA512 SRI|distfile records."])
        lines.append(f"NIMBALYST_NPM_{group.upper()}=(")
        for identifier, integrity, filename, _ in groups[group]:
            lines.append(f'\t"{identifier}|{integrity}|{filename}"')
        lines.extend([")", ""])
    lines.extend(["# @FUNCTION: nimbalyst_npm_src_uri", "# @DESCRIPTION:",
                  "# Append the exact registry inputs to SRC_URI, with architecture",
                  "# conditionals for native dependencies. Call after defining SRC_URI.",
                  "nimbalyst_npm_src_uri() {", "\tSRC_URI+=\" "])
    for group in ("common", "amd64", "arm64"):
        if group != "common":
            lines.append(f"\t\t{group}? (")
        for _, _, filename, uri in groups[group]:
            lines.append(f"\t\t{uri} -> {filename}")
        if group != "common":
            lines.append("\t\t)")
    lines.extend(['\t"', "}", ""])
    output.write_text("\n".join(lines))
    print({group: len(entries) for group, entries in groups.items()})


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    generate(args.source, args.output)
