#!/usr/bin/env python3
"""Generate JupyterLab Desktop's individual Yarn v1 distfiles from upstream's lock."""
import argparse
import re
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('lock', type=Path)
parser.add_argument('output', type=Path)
args = parser.parse_args()
urls = sorted(set(re.findall(r'^  resolved "([^"#]+)', args.lock.read_text(), re.M)))
lines = [
    '# Copyright 2026 Gentoo Authors',
    '# Distributed under the terms of the GNU General Public License v2',
    '',
    '# @ECLASS: jupyterlab-desktop-yarn-deps-4.6.3_p1.eclass',
    '# @MAINTAINER:',
    '# Leonid Kopylov <leonchik1976@gmail.com>',
    '# @SUPPORTED_EAPIS: 8',
    '# @BLURB: Locked upstream Yarn distfiles for JupyterLab Desktop',
    '# Generated by scripts/generate-jupyterlab-desktop-yarn-deps.py.',
    '',
    'JUPYTERLAB_DESKTOP_YARN_SRC_URI="',
]
seen = {}
for url in urls:
    if not url.startswith('https://registry.yarnpkg.com/'):
        raise SystemExit(f'Unexpected registry: {url}')
    name = url.split('registry.yarnpkg.com/', 1)[1].split('/-/')[0]
    basename = url.rsplit('/', 1)[1]
    filename = name.split('/')[0] + '-' + basename if name.startswith('@') else basename
    if filename in seen and seen[filename] != url:
        raise SystemExit(f'Distfile collision: {filename}')
    seen[filename] = url
    lines.append(f'\t{url}' + (f' -> {filename}' if filename != basename else ''))
lines.extend(['"', '', '# @FUNCTION: jupyterlab_desktop_yarn_src_uri', '# @DESCRIPTION:', '# Append the release-locked Yarn archives to SRC_URI.', 'jupyterlab_desktop_yarn_src_uri() {', '\tSRC_URI+=" ${JUPYTERLAB_DESKTOP_YARN_SRC_URI}"', '}', ''])
args.output.write_text('\n'.join(lines))
print(f'Generated {len(urls)} locked Yarn distfiles')
